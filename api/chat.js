export default async function handler(req, res) {
  res.setHeader('Access-Control-Allow-Origin', '*');
  res.setHeader('Access-Control-Allow-Methods', 'POST, OPTIONS');
  res.setHeader('Access-Control-Allow-Headers', 'Content-Type');
  if (req.method === 'OPTIONS') {
    res.status(200).end();
    return;
  }
  if (req.method !== 'POST') {
    res.status(405).json({ error: 'Method not allowed' });
    return;
  }
  const ip = (req.headers['x-forwarded-for'] || '').split(',')[0].trim() || req.socket?.remoteAddress || 'unknown';
  const now = Date.now();
  let record = rateLimitMap.get(ip);
  if (!record || now > record.resetAt) {
    record = { count: 0, resetAt: now + WINDOW_MS };
  }
  record.count++;
  rateLimitMap.set(ip, record);
  if (record.count > RATE_LIMIT) {
    res.status(429).json({ error: 'Too many requests. Please wait a minute before asking again.' });
    return;
  }
  const apiKey = process.env.GROQ_API_KEY;
  if (!apiKey) {
    res.status(500).json({ error: 'Server configuration error. Please try again later.' });
    return;
  }
  const { messages } = req.body || {};
  if (!messages || !Array.isArray(messages) || messages.length === 0) {
    res.status(400).json({ error: 'Invalid request.' });
    return;
  }
  const fullMessages = [{ role: 'system', content: SYSTEM_PROMPT }, ...messages.slice(-20)];
  try {
    let groqRes = await fetch('https://api.groq.com/openai/v1/chat/completions', {
      method: 'POST',
      headers: {
        'Content-Type': 'application/json',
        'Authorization': `Bearer ${apiKey}`
      },
      body: JSON.stringify({
        model: 'llama-3.1-8b-instant',
        messages: fullMessages,
        temperature: 0.3,
        max_tokens: 1024
      })
    });
    let data = await groqRes.json();
    if (!groqRes.ok && data.error?.code === 'model_not_found') {
      groqRes = await fetch('https://api.groq.com/openai/v1/chat/completions', {
        method: 'POST',
        headers: {
          'Content-Type': 'application/json',
          'Authorization': `Bearer ${apiKey}`
        },
        body: JSON.stringify({
          model: 'llama3-8b-8192',
          messages: fullMessages,
          temperature: 0.3,
          max_tokens: 1024
        })
      });
      data = await groqRes.json();
    }
    if (!groqRes.ok || data.error) {
      res.status(502).json({ error: data.error?.message || 'Failed to get a response. Please try again.' });
      return;
    }
    const reply = data.choices?.[0]?.message?.content || 'No response generated.';
    res.status(200).json({ reply });
  } catch {
    res.status(500).json({ error: 'Network error. Please check your connection and try again.' });
  }
}